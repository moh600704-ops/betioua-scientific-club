function applyLanguage(lang) {
  const activeLang = translations[lang] ? lang : "ar";
  const dict = translations[activeLang];

  document.documentElement.lang = activeLang;
  document.documentElement.dir = activeLang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  localStorage.setItem("bsc_lang", activeLang);
}

function initHeroTelemetryCanvas() {
  const canvas = document.getElementById("heroTelemetryCanvas");
  if (!canvas) return;

  const ctx = canvas.getContext("2d");
  if (!ctx) return;

  let width = 0;
  let height = 0;
  let animId = null;
  const nodeCount = window.innerWidth < 768 ? 22 : 42;
  const maxDist = window.innerWidth < 768 ? 110 : 150;
  const nodes = [];

  function resize() {
    const rect = canvas.parentElement.getBoundingClientRect();
    width = canvas.width = rect.width;
    height = canvas.height = rect.height;
  }

  resize();
  window.addEventListener("resize", resize);

  for (let i = 0; i < nodeCount; i++) {
    nodes.push({
      x: Math.random() * width,
      y: Math.random() * height,
      vx: (Math.random() - 0.5) * 0.45,
      vy: (Math.random() - 0.5) * 0.45,
      amber: i % 5 === 0
    });
  }

  function render() {
    ctx.clearRect(0, 0, width, height);

    for (let i = 0; i < nodes.length; i++) {
      const a = nodes[i];
      a.x += a.vx;
      a.y += a.vy;

      if (a.x < 0 || a.x > width) a.vx *= -1;
      if (a.y < 0 || a.y > height) a.vy *= -1;

      for (let j = i + 1; j < nodes.length; j++) {
        const b = nodes[j];
        const dx = a.x - b.x;
        const dy = a.y - b.y;
        const dist = Math.hypot(dx, dy);

        if (dist < maxDist) {
          const alpha = (1 - dist / maxDist) * 0.28;
          ctx.strokeStyle = a.amber || b.amber
            ? `rgba(249, 115, 22, ${alpha})`
            : `rgba(56, 189, 248, ${alpha})`;
          ctx.lineWidth = 1;
          ctx.beginPath();
          ctx.moveTo(a.x, a.y);
          ctx.lineTo(b.x, b.y);
          ctx.stroke();
        }
      }

      ctx.fillStyle = a.amber ? "rgba(251, 146, 60, 0.75)" : "rgba(56, 189, 248, 0.75)";
      ctx.beginPath();
      ctx.arc(a.x, a.y, a.amber ? 2.1 : 1.7, 0, Math.PI * 2);
      ctx.fill();
    }

    animId = requestAnimationFrame(render);
  }

  document.addEventListener("visibilitychange", () => {
    if (document.hidden && animId) {
      cancelAnimationFrame(animId);
      animId = null;
    } else if (!document.hidden && !animId) {
      render();
    }
  });

  render();
}

document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem("bsc_lang") || "ar";
  applyLanguage(savedLang);

  const toggleBtn = document.getElementById("langToggleBtn");
  if (toggleBtn) {
    toggleBtn.addEventListener("click", () => {
      const current = document.documentElement.lang === "en" ? "en" : "ar";
      const next = current === "ar" ? "en" : "ar";
      applyLanguage(next);
    });
  }

  // Highlight active navigation link safely
  const currentFile = window.location.pathname.split("/").pop() || "index.html";
  document.querySelectorAll("[data-nav]").forEach((link) => {
    const target = link.getAttribute("data-nav");
    link.classList.toggle("active", target === currentFile);
  });

  // Safe contact form handler if present on contact.html
  const contactForm = document.getElementById("contactForm");
  if (contactForm) {
    contactForm.addEventListener("submit", (e) => {
      e.preventDefault();
      const isEn = document.documentElement.lang === "en";
      alert(
        isEn
          ? "Thank you. Official email routing is being finalized with the institute administration."
          : "شكراً لتواصلك. قنوات البريد الإلكتروني الرسمية قيد التفعيل النهائي مع إدارة المعهد."
      );
    });
  }

  // Start lightweight engineering telemetry background on Home
  initHeroTelemetryCanvas();
});
